#include <stdlib.h>
#include <stdio.h>
#include "operations.h"

int add(int nb1, int nb2) {
	return nb1+nb2;
}
int sub(int nb1, int nb2) {
	return nb1-nb2;
}
int mul(int nb1, int nb2) {
	return nb1*nb2;
}
int divide(int nb1, int nb2) {
	return nb1/nb2;
}
int mod(int nb1, int nb2) {
	return nb1%nb2;
}

